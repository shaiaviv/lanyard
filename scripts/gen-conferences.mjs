// Emits scripts/additional-conferences.sql from the shared transform.
import { writeFileSync } from 'node:fs';
import { buildConferenceRows } from './build-conferences.mjs';

const sq = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (xs) => `'{${xs.map((x) => `"${x}"`).join(',')}}'`;

const { rows, skipped } = buildConferenceRows();

const values = rows.map((r) =>
  `  (${sq(r.name)},'${r.start_date}','${r.end_date}',${sq(r.location)},${sq(r.country)},` +
  `${sq(r.region)},${arr(r.verticals)},${r.est_audience},${r.latitude},${r.longitude},` +
  `${r.icp_score},'${r.tier}',${sq(JSON.stringify(r.score_breakdown))}::jsonb)`
);

const sql =
  '-- Additional REAL conferences (H2 2026 + full 2027). Generated by scripts/gen-conferences.mjs\n' +
  '-- Scored with the same weighted formula as lib/scoring/computeIcpScore.ts. Do not edit by hand.\n' +
  'insert into conferences (name, start_date, end_date, location, country, region, verticals, est_audience, latitude, longitude, icp_score, tier, score_breakdown) values\n' +
  values.join(',\n') + '\n' +
  'on conflict do nothing;\n';

writeFileSync(new URL('./additional-conferences.sql', import.meta.url), sql);

const tiers = rows.reduce((m, r) => { m[r.tier] = (m[r.tier]||0)+1; return m; }, {});
console.log(`emitted ${rows.length} new conferences  tiers=${JSON.stringify(tiers)}`);
console.log(`skipped: existing=${skipped.existing.length} intra-dupe=${skipped.dupe.length} out-of-window=${skipped.outOfWindow.length}`);
